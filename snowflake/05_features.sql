-- 05_features.sql
-- Features and the days-until-failure label, one row per 10-minute reading.
-- Role: INDUSTRIAL_TRANSFORM.
--
-- How the table is built:
--   CYCLE_ID         counts failures before a reading. Every window stops at the
--                    cycle border, so after a repair the model never sees readings
--                    from before the repair.
--   NEXT_FAILURE_TS  time of the machine's next failure; RUL_DAYS is that time minus
--                    now, empty after a machine's last failure (nobody knows the next one).
--   Windows look backwards only (1 h, 6 h, 24 h). Failure rows are labels, not rows.
--   Each machine's "normal" vibration and temperature come from the first 20 days
--   only (10th percentile), so the test period never leaks into the training data.
--   The first day of every cycle is dropped because the 24 h windows are not full yet.
--   SPLIT: first 20 days TRAIN, the rest TEST. train_rul.py also drops training rows
--   whose next failure lies behind the 20-day line.

USE WAREHOUSE INDUSTRIAL_WH;

CREATE OR REPLACE DYNAMIC TABLE INDUSTRIAL_LAKEHOUSE.GOLD.FEATURES_RUL
  TARGET_LAG = '1 hour' WAREHOUSE = INDUSTRIAL_WH REFRESH_MODE = FULL
AS
WITH bounds AS (
  SELECT MIN(READING_TIMESTAMP) AS T0
  FROM INDUSTRIAL_LAKEHOUSE.SILVER.SILVER_TELEMETRY
),
base AS (
  SELECT s.MACHINE_ID,
         PERCENTILE_CONT(0.1) WITHIN GROUP (ORDER BY s.VIBRATION_RMS) AS BASE_VIB,
         PERCENTILE_CONT(0.1) WITHIN GROUP (ORDER BY s.TEMP_C)        AS BASE_TEMP
  FROM INDUSTRIAL_LAKEHOUSE.SILVER.SILVER_TELEMETRY s CROSS JOIN bounds b
  WHERE s.READING_TIMESTAMP < DATEADD('day', 20, b.T0) AND NOT s.FAILURE_SPIKE
  GROUP BY s.MACHINE_ID
),
cycles AS (
  SELECT s.*,
    COALESCE(SUM(CASE WHEN FAILURE_SPIKE THEN 1 ELSE 0 END) OVER (
      PARTITION BY MACHINE_ID ORDER BY READING_TIMESTAMP
      ROWS BETWEEN UNBOUNDED PRECEDING AND 1 PRECEDING), 0) AS CYCLE_ID,
    MIN(CASE WHEN FAILURE_SPIKE THEN READING_TIMESTAMP END) OVER (
      PARTITION BY MACHINE_ID ORDER BY READING_TIMESTAMP
      ROWS BETWEEN 1 FOLLOWING AND UNBOUNDED FOLLOWING) AS NEXT_FAILURE_TS
  FROM INDUSTRIAL_LAKEHOUSE.SILVER.SILVER_TELEMETRY s
),
feat AS (
  SELECT c.*,
    AVG(VIBRATION_RMS) OVER (PARTITION BY MACHINE_ID, CYCLE_ID ORDER BY READING_TIMESTAMP
      RANGE BETWEEN INTERVAL '1 hour'   PRECEDING AND CURRENT ROW) AS VIB_MEAN_1H,
    AVG(VIBRATION_RMS) OVER (PARTITION BY MACHINE_ID, CYCLE_ID ORDER BY READING_TIMESTAMP
      RANGE BETWEEN INTERVAL '6 hours'  PRECEDING AND CURRENT ROW) AS VIB_MEAN_6H,
    AVG(VIBRATION_RMS) OVER (PARTITION BY MACHINE_ID, CYCLE_ID ORDER BY READING_TIMESTAMP
      RANGE BETWEEN INTERVAL '24 hours' PRECEDING AND CURRENT ROW) AS VIB_MEAN_24H,
    STDDEV(VIBRATION_RMS) OVER (PARTITION BY MACHINE_ID, CYCLE_ID ORDER BY READING_TIMESTAMP
      RANGE BETWEEN INTERVAL '6 hours'  PRECEDING AND CURRENT ROW) AS VIB_STD_6H,
    AVG(TEMP_C) OVER (PARTITION BY MACHINE_ID, CYCLE_ID ORDER BY READING_TIMESTAMP
      RANGE BETWEEN INTERVAL '1 hour'   PRECEDING AND CURRENT ROW) AS TEMP_MEAN_1H,
    AVG(TEMP_C) OVER (PARTITION BY MACHINE_ID, CYCLE_ID ORDER BY READING_TIMESTAMP
      RANGE BETWEEN INTERVAL '6 hours'  PRECEDING AND CURRENT ROW) AS TEMP_MEAN_6H,
    AVG(TEMP_C) OVER (PARTITION BY MACHINE_ID, CYCLE_ID ORDER BY READING_TIMESTAMP
      RANGE BETWEEN INTERVAL '24 hours' PRECEDING AND CURRENT ROW) AS TEMP_MEAN_24H,
    AVG(POWER_KW) OVER (PARTITION BY MACHINE_ID, CYCLE_ID ORDER BY READING_TIMESTAMP
      RANGE BETWEEN INTERVAL '6 hours'  PRECEDING AND CURRENT ROW) AS POWER_MEAN_6H,
    SUM(CASE WHEN DEGRADATION THEN 1 ELSE 0 END) OVER (
      PARTITION BY MACHINE_ID, CYCLE_ID ORDER BY READING_TIMESTAMP
      RANGE BETWEEN INTERVAL '24 hours' PRECEDING AND CURRENT ROW) AS DEGRADATION_FLAGS_24H,
    DATEDIFF('minute',
      MIN(READING_TIMESTAMP) OVER (PARTITION BY MACHINE_ID, CYCLE_ID),
      READING_TIMESTAMP) / 1440.0 AS DAYS_IN_CYCLE
  FROM cycles c
)
SELECT
  f.READING_TIMESTAMP, f.MACHINE_ID,
  REGEXP_REPLACE(f.MACHINE_ID, '_[0-9]+$', '')   AS MACHINE_GROUP,
  f.CYCLE_ID,
  f.VIB_MEAN_1H, f.VIB_MEAN_6H, f.VIB_MEAN_24H, f.VIB_STD_6H,
  f.VIB_MEAN_6H - f.VIB_MEAN_24H                 AS VIB_TREND,
  f.VIB_MEAN_1H / b.BASE_VIB                     AS VIB_RATIO_TO_NORMAL,
  f.TEMP_MEAN_1H, f.TEMP_MEAN_6H, f.TEMP_MEAN_24H,
  f.TEMP_MEAN_6H - f.TEMP_MEAN_24H               AS TEMP_TREND,
  f.TEMP_MEAN_1H - b.BASE_TEMP                   AS TEMP_ABOVE_NORMAL,
  f.POWER_MEAN_6H, f.DEGRADATION_FLAGS_24H,
  CASE WHEN f.CYCLE_ID > 0 THEN f.DAYS_IN_CYCLE END AS DAYS_SINCE_REPAIR,
  f.NEXT_FAILURE_TS,
  DATEDIFF('second', f.READING_TIMESTAMP, f.NEXT_FAILURE_TS) / 86400.0 AS RUL_DAYS,
  CASE WHEN f.READING_TIMESTAMP < DATEADD('day', 20, bd.T0)
       THEN 'TRAIN' ELSE 'TEST' END              AS SPLIT
FROM feat f
JOIN base b   ON b.MACHINE_ID = f.MACHINE_ID
CROSS JOIN bounds bd
WHERE NOT f.FAILURE_SPIKE
  AND f.DAYS_IN_CYCLE >= 1;

