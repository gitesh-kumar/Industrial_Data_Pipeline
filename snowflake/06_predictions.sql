-- 06_predictions.sql
-- Predictions table, the role that may write it, and the Gold view with maintenance priority.
--
-- The model itself lives in Python (models/rul_sensors.joblib, trained by train_rul.py).
-- score_rul.py reads GOLD.FEATURES_RUL, scores it and writes GOLD.RUL_PREDICTIONS.
-- Snowflake only stores and joins the result. Scoring is a batch job, not live.

-- ── Part 1: table and grants. Role: INDUSTRIAL_ENGINEER ───────────
USE ROLE INDUSTRIAL_ENGINEER;

CREATE TABLE IF NOT EXISTS INDUSTRIAL_LAKEHOUSE.GOLD.RUL_PREDICTIONS (
  READING_TIMESTAMP  TIMESTAMP_NTZ,
  MACHINE_ID         STRING,
  PREDICTED_RUL_DAYS FLOAT,
  MODEL_VERSION      STRING,
  SCORED_AT          TIMESTAMP_NTZ
);

GRANT SELECT ON DYNAMIC TABLE INDUSTRIAL_LAKEHOUSE.GOLD.FEATURES_RUL TO ROLE INDUSTRIAL_ML;
GRANT SELECT ON DYNAMIC TABLE INDUSTRIAL_LAKEHOUSE.GOLD.FEATURES_RUL TO ROLE INDUSTRIAL_READER;
GRANT SELECT, INSERT, TRUNCATE ON TABLE INDUSTRIAL_LAKEHOUSE.GOLD.RUL_PREDICTIONS TO ROLE INDUSTRIAL_ML;
GRANT SELECT ON TABLE INDUSTRIAL_LAKEHOUSE.GOLD.RUL_PREDICTIONS TO ROLE INDUSTRIAL_TRANSFORM;
GRANT SELECT ON TABLE INDUSTRIAL_LAKEHOUSE.GOLD.RUL_PREDICTIONS TO ROLE INDUSTRIAL_READER;

-- ── Part 2: run score_rul.py now, then continue ───────────────────

-- ── Part 3: Gold table with priority. Role: INDUSTRIAL_TRANSFORM ──
-- The rule recommendation stays untouched next to the model output.
-- A machine whose newest prediction is more than 6 hours older than its newest
-- reading was just repaired: it shows WARMING_UP and no number.
-- Priority bands (days left): under 1.5 URGENT, under 3 SOON, under 5 WATCH, else OK.
-- These bands are starting values, not derived from data.
USE ROLE INDUSTRIAL_TRANSFORM;
USE WAREHOUSE INDUSTRIAL_WH;

CREATE OR REPLACE DYNAMIC TABLE INDUSTRIAL_LAKEHOUSE.GOLD.GOLD_PREDICTIVE_STATUS
  TARGET_LAG = '1 hour' WAREHOUSE = INDUSTRIAL_WH REFRESH_MODE = FULL
AS
WITH latest_reading AS (
  SELECT MACHINE_ID, MAX(READING_TIMESTAMP) AS LAST_READING
  FROM INDUSTRIAL_LAKEHOUSE.SILVER.SILVER_TELEMETRY
  GROUP BY MACHINE_ID
),
latest_pred AS (
  SELECT MACHINE_ID, READING_TIMESTAMP AS PRED_FOR_READING,
         PREDICTED_RUL_DAYS, MODEL_VERSION, SCORED_AT
  FROM INDUSTRIAL_LAKEHOUSE.GOLD.RUL_PREDICTIONS
  QUALIFY ROW_NUMBER() OVER (PARTITION BY MACHINE_ID ORDER BY READING_TIMESTAMP DESC) = 1
)
SELECT
  g.MACHINE_ID, g.MACHINE_TYPE,
  g.RECOMMENDATION AS RULE_RECOMMENDATION,
  g.EFFICIENCY_STATUS, g.HOURLY_ENERGY_COST_EUR, g.AVG_RISK_SCORE,
  r.LAST_READING, p.PRED_FOR_READING, p.MODEL_VERSION,
  CASE WHEN DATEDIFF('hour', p.PRED_FOR_READING, r.LAST_READING) > 6
            OR p.PRED_FOR_READING IS NULL THEN NULL
       ELSE p.PREDICTED_RUL_DAYS END AS PREDICTED_RUL_DAYS,
  CASE WHEN p.PRED_FOR_READING IS NULL
            OR DATEDIFF('hour', p.PRED_FOR_READING, r.LAST_READING) > 6 THEN 'WARMING_UP'
       WHEN p.PREDICTED_RUL_DAYS < 1.5 THEN 'URGENT'
       WHEN p.PREDICTED_RUL_DAYS < 3   THEN 'SOON'
       WHEN p.PREDICTED_RUL_DAYS < 5   THEN 'WATCH'
       ELSE 'OK' END AS MAINTENANCE_PRIORITY
FROM INDUSTRIAL_LAKEHOUSE.GOLD.GOLD_OPERATIONS_STATUS g
JOIN latest_reading r ON r.MACHINE_ID = g.MACHINE_ID
LEFT JOIN latest_pred p ON p.MACHINE_ID = g.MACHINE_ID;

