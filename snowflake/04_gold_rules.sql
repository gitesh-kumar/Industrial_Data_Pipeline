-- 04_gold_rules.sql
-- Rule-based Gold layer. Role: INDUSTRIAL_TRANSFORM.
--
-- Same rules as src/gold_analytics.py:
--   avg temp > 100 -> CRITICAL, > 80 -> WARNING, else OPTIMAL
--   CRITICAL -> IMMEDIATE_SHUTDOWN; more than 3 failure spikes -> SCHEDULE_MAINTENANCE;
--   WARNING and price > 200 EUR/MWh -> REDUCE_LOAD; otherwise CONTINUE
-- Cost per hour = average power in MW times the latest market price.
-- These rules are the baseline the model in 05 and 06 is compared against.
--
-- Re-run this file whenever 02_silver.sql is recreated.

USE WAREHOUSE INDUSTRIAL_WH;

CREATE OR REPLACE DYNAMIC TABLE INDUSTRIAL_LAKEHOUSE.GOLD.GOLD_OPERATIONS_STATUS
  TARGET_LAG = '1 hour'
  WAREHOUSE  = INDUSTRIAL_WH
AS
WITH price AS (
  -- the newest market price
  SELECT PRICE_EUR_MWH
  FROM INDUSTRIAL_LAKEHOUSE.BRONZE.ENERGY_PRICE
  QUALIFY ROW_NUMBER() OVER (ORDER BY PRICE_TIMESTAMP DESC) = 1
),
agg AS (
  -- one row per machine
  SELECT
    MACHINE_ID, MACHINE_TYPE,
    COUNT(*)              AS TOTAL_READINGS,
    AVG(POWER_KW)         AS AVG_POWER_USAGE,
    MAX(POWER_KW)         AS PEAK_POWER_KW,
    AVG(TEMP_C)           AS AVG_TEMP,
    MAX(TEMP_C)           AS MAX_TEMP,
    AVG(VIBRATION_RMS)    AS AVG_VIBRATION,
    MAX(VIBRATION_RMS)    AS MAX_VIBRATION,
    AVG(RISK_SCORE)       AS AVG_RISK_SCORE,
    MAX(RISK_SCORE)       AS MAX_RISK_SCORE,
    SUM(CASE WHEN QUALITY_FLAG = 'FAILURE_SPIKE'    THEN 1 ELSE 0 END) AS FAILURE_SPIKE_COUNT,
    SUM(CASE WHEN QUALITY_FLAG = 'DEGRADATION_WARN' THEN 1 ELSE 0 END) AS DEGRADATION_COUNT
  FROM INDUSTRIAL_LAKEHOUSE.SILVER.SILVER_TELEMETRY
  GROUP BY MACHINE_ID, MACHINE_TYPE
),
status AS (
  SELECT agg.*,
    CASE WHEN AVG_TEMP > 100 THEN 'CRITICAL'
         WHEN AVG_TEMP > 80  THEN 'WARNING'
         ELSE 'OPTIMAL' END AS EFFICIENCY_STATUS
  FROM agg
)
SELECT
  s.*,
  ROUND(s.AVG_POWER_USAGE / 1000 * p.PRICE_EUR_MWH, 4) AS HOURLY_ENERGY_COST_EUR,
  CASE WHEN s.EFFICIENCY_STATUS = 'CRITICAL'                           THEN 'IMMEDIATE_SHUTDOWN'
       WHEN s.FAILURE_SPIKE_COUNT > 3                                  THEN 'SCHEDULE_MAINTENANCE'
       WHEN s.EFFICIENCY_STATUS = 'WARNING' AND p.PRICE_EUR_MWH > 200  THEN 'REDUCE_LOAD'
       ELSE 'CONTINUE' END AS RECOMMENDATION,
  p.PRICE_EUR_MWH AS ENERGY_PRICE_EUR_MWH
FROM status s CROSS JOIN price p;