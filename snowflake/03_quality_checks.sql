-- Data metric functions (data quality checks) on SILVER_TELEMETRY.
--
-- The three function bodies are copied from the deployed functions (DESC FUNCTION).
-- The grant lines and the ATTACH statements are the ones that ran in the worksheet
-- sessions, rebuilt from notes.
--
-- Do not run Part 1 on an account where the checks are already attached:
-- replacing a function that is in use can fail. Part 2 is needed again whenever
-- 02_silver.sql is recreated, because recreating Silver drops its checks.

-- ── Part 1: custom checks. Role: INDUSTRIAL_ENGINEER ──────────────
USE ROLE INDUSTRIAL_ENGINEER;

-- Rows that repeat the same machine at the same moment
CREATE OR REPLACE DATA METRIC FUNCTION INDUSTRIAL_LAKEHOUSE.SILVER.DUPLICATE_READINGS(
  arg_t TABLE(machine_id VARCHAR, reading_ts TIMESTAMP_NTZ))
RETURNS NUMBER AS
$$ SELECT COUNT(*) - COUNT(DISTINCT machine_id, reading_ts) FROM arg_t $$;

-- Readings outside physically possible limits (vibration 0-50, temperature -50-200, power 0-200)
CREATE OR REPLACE DATA METRIC FUNCTION INDUSTRIAL_LAKEHOUSE.SILVER.OUT_OF_RANGE_READINGS(
  arg_t TABLE(vib FLOAT, temp FLOAT, pwr FLOAT))
RETURNS NUMBER AS
$$ SELECT COUNT(*) FROM arg_t
   WHERE vib < 0 OR vib > 50 OR temp < -50 OR temp > 200 OR pwr < 0 OR pwr > 200 $$;

-- Seconds between the newest reading and the scheduled check time.
-- Timestamps are Berlin local time, so the check time is converted to Berlin time.
CREATE OR REPLACE DATA METRIC FUNCTION INDUSTRIAL_LAKEHOUSE.SILVER.DATA_FRESHNESS_SECONDS(
  arg_t TABLE(ts TIMESTAMP_NTZ))
RETURNS NUMBER AS
$$ SELECT DATEDIFF('second', MAX(ts),
   CONVERT_TIMEZONE('Europe/Berlin', SNOWFLAKE.CORE.DATA_METRIC_SCHEDULED_TIME())::TIMESTAMP_NTZ) FROM arg_t $$;

GRANT USAGE ON FUNCTION INDUSTRIAL_LAKEHOUSE.SILVER.DUPLICATE_READINGS(TABLE(VARCHAR, TIMESTAMP_NTZ))
  TO ROLE INDUSTRIAL_TRANSFORM;
GRANT USAGE ON FUNCTION INDUSTRIAL_LAKEHOUSE.SILVER.OUT_OF_RANGE_READINGS(TABLE(FLOAT, FLOAT, FLOAT))
  TO ROLE INDUSTRIAL_TRANSFORM;
GRANT USAGE ON FUNCTION INDUSTRIAL_LAKEHOUSE.SILVER.DATA_FRESHNESS_SECONDS(TABLE(TIMESTAMP_NTZ))
  TO ROLE INDUSTRIAL_TRANSFORM;

-- ── Part 2: attach all eight checks. Role: INDUSTRIAL_TRANSFORM ───
USE ROLE INDUSTRIAL_TRANSFORM;
USE WAREHOUSE INDUSTRIAL_WH;

-- The schedule has to be set before any check is attached.
ALTER DYNAMIC TABLE INDUSTRIAL_LAKEHOUSE.SILVER.SILVER_TELEMETRY
  SET DATA_METRIC_SCHEDULE = '60 MINUTE';

ALTER DYNAMIC TABLE INDUSTRIAL_LAKEHOUSE.SILVER.SILVER_TELEMETRY
  ADD DATA METRIC FUNCTION SNOWFLAKE.CORE.NULL_COUNT ON (READING_TIMESTAMP);
ALTER DYNAMIC TABLE INDUSTRIAL_LAKEHOUSE.SILVER.SILVER_TELEMETRY
  ADD DATA METRIC FUNCTION SNOWFLAKE.CORE.NULL_COUNT ON (MACHINE_ID);
ALTER DYNAMIC TABLE INDUSTRIAL_LAKEHOUSE.SILVER.SILVER_TELEMETRY
  ADD DATA METRIC FUNCTION SNOWFLAKE.CORE.NULL_COUNT ON (VIBRATION_RMS);
ALTER DYNAMIC TABLE INDUSTRIAL_LAKEHOUSE.SILVER.SILVER_TELEMETRY
  ADD DATA METRIC FUNCTION SNOWFLAKE.CORE.NULL_COUNT ON (TEMP_C);
ALTER DYNAMIC TABLE INDUSTRIAL_LAKEHOUSE.SILVER.SILVER_TELEMETRY
  ADD DATA METRIC FUNCTION SNOWFLAKE.CORE.ROW_COUNT ON ();

ALTER DYNAMIC TABLE INDUSTRIAL_LAKEHOUSE.SILVER.SILVER_TELEMETRY
  ADD DATA METRIC FUNCTION INDUSTRIAL_LAKEHOUSE.SILVER.DUPLICATE_READINGS
  ON (MACHINE_ID, READING_TIMESTAMP);
ALTER DYNAMIC TABLE INDUSTRIAL_LAKEHOUSE.SILVER.SILVER_TELEMETRY
  ADD DATA METRIC FUNCTION INDUSTRIAL_LAKEHOUSE.SILVER.OUT_OF_RANGE_READINGS
  ON (VIBRATION_RMS, TEMP_C, POWER_KW);
ALTER DYNAMIC TABLE INDUSTRIAL_LAKEHOUSE.SILVER.SILVER_TELEMETRY
  ADD DATA METRIC FUNCTION INDUSTRIAL_LAKEHOUSE.SILVER.DATA_FRESHNESS_SECONDS
  ON (READING_TIMESTAMP);

