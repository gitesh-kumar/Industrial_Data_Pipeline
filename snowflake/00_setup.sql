-- 00_setup.sql
-- Roles, warehouse, database, schemas, grants and the loader service user.
--
-- NOTE: rebuilt from the worksheet sessions, not copied from the original run.
-- Check a fresh run against your account with SHOW GRANTS TO ROLE <role>.
--
-- Run order: this file first, as ACCOUNTADMIN (the role dropdown, not just USE ROLE).

USE ROLE ACCOUNTADMIN;

-- ── Roles ─────────────────────────────────────────────────────────
-- ENGINEER  owns the database and the check functions, grants access
-- INGEST    writes raw data into BRONZE, nothing else
-- TRANSFORM reads BRONZE, owns the SILVER and GOLD dynamic tables
-- READER    read-only, used by the API and dashboards
-- ML        reads the features table, writes the predictions table
CREATE ROLE IF NOT EXISTS INDUSTRIAL_ENGINEER;
CREATE ROLE IF NOT EXISTS INDUSTRIAL_INGEST;
CREATE ROLE IF NOT EXISTS INDUSTRIAL_TRANSFORM;
CREATE ROLE IF NOT EXISTS INDUSTRIAL_READER;
CREATE ROLE IF NOT EXISTS INDUSTRIAL_ML;

-- Replace with your own Snowflake user name (lowercase names need double quotes).
GRANT ROLE INDUSTRIAL_ENGINEER  TO USER "<YOUR_SNOWFLAKE_USER>";
GRANT ROLE INDUSTRIAL_INGEST    TO USER "<YOUR_SNOWFLAKE_USER>";
GRANT ROLE INDUSTRIAL_TRANSFORM TO USER "<YOUR_SNOWFLAKE_USER>";
GRANT ROLE INDUSTRIAL_READER    TO USER "<YOUR_SNOWFLAKE_USER>";
GRANT ROLE INDUSTRIAL_ML        TO USER "<YOUR_SNOWFLAKE_USER>";

-- ── Warehouse ─────────────────────────────────────────────────────
CREATE WAREHOUSE IF NOT EXISTS INDUSTRIAL_WH
  WAREHOUSE_SIZE      = 'XSMALL'
  AUTO_SUSPEND        = 60
  AUTO_RESUME         = TRUE
  INITIALLY_SUSPENDED = TRUE;

GRANT USAGE ON WAREHOUSE INDUSTRIAL_WH TO ROLE INDUSTRIAL_ENGINEER;
GRANT USAGE ON WAREHOUSE INDUSTRIAL_WH TO ROLE INDUSTRIAL_INGEST;
GRANT USAGE ON WAREHOUSE INDUSTRIAL_WH TO ROLE INDUSTRIAL_TRANSFORM;
GRANT USAGE ON WAREHOUSE INDUSTRIAL_WH TO ROLE INDUSTRIAL_READER;
GRANT USAGE ON WAREHOUSE INDUSTRIAL_WH TO ROLE INDUSTRIAL_ML;

-- ── Database and schemas (owned by ENGINEER) ──────────────────────
GRANT CREATE DATABASE ON ACCOUNT TO ROLE INDUSTRIAL_ENGINEER;
GRANT EXECUTE DATA METRIC FUNCTION ON ACCOUNT TO ROLE INDUSTRIAL_TRANSFORM;
GRANT DATABASE ROLE SNOWFLAKE.DATA_METRIC_USER TO ROLE INDUSTRIAL_TRANSFORM;
GRANT APPLICATION ROLE SNOWFLAKE.DATA_QUALITY_MONITORING_VIEWER TO ROLE INDUSTRIAL_ENGINEER;

USE ROLE INDUSTRIAL_ENGINEER;

CREATE DATABASE IF NOT EXISTS INDUSTRIAL_LAKEHOUSE;
CREATE SCHEMA IF NOT EXISTS INDUSTRIAL_LAKEHOUSE.BRONZE;
CREATE SCHEMA IF NOT EXISTS INDUSTRIAL_LAKEHOUSE.SILVER;
CREATE SCHEMA IF NOT EXISTS INDUSTRIAL_LAKEHOUSE.GOLD;

-- Everybody needs to see the database.
GRANT USAGE ON DATABASE INDUSTRIAL_LAKEHOUSE TO ROLE INDUSTRIAL_INGEST;
GRANT USAGE ON DATABASE INDUSTRIAL_LAKEHOUSE TO ROLE INDUSTRIAL_TRANSFORM;
GRANT USAGE ON DATABASE INDUSTRIAL_LAKEHOUSE TO ROLE INDUSTRIAL_READER;
GRANT USAGE ON DATABASE INDUSTRIAL_LAKEHOUSE TO ROLE INDUSTRIAL_ML;

-- INGEST: creates and fills tables in BRONZE only
GRANT USAGE        ON SCHEMA INDUSTRIAL_LAKEHOUSE.BRONZE TO ROLE INDUSTRIAL_INGEST;
GRANT CREATE TABLE ON SCHEMA INDUSTRIAL_LAKEHOUSE.BRONZE TO ROLE INDUSTRIAL_INGEST;

-- TRANSFORM: reads BRONZE (now and for tables created later), builds SILVER and GOLD
GRANT USAGE ON SCHEMA INDUSTRIAL_LAKEHOUSE.BRONZE TO ROLE INDUSTRIAL_TRANSFORM;
GRANT SELECT ON ALL    TABLES IN SCHEMA INDUSTRIAL_LAKEHOUSE.BRONZE TO ROLE INDUSTRIAL_TRANSFORM;
GRANT SELECT ON FUTURE TABLES IN SCHEMA INDUSTRIAL_LAKEHOUSE.BRONZE TO ROLE INDUSTRIAL_TRANSFORM;

GRANT USAGE, CREATE TABLE, CREATE DYNAMIC TABLE ON SCHEMA INDUSTRIAL_LAKEHOUSE.SILVER TO ROLE INDUSTRIAL_TRANSFORM;
GRANT USAGE, CREATE TABLE, CREATE DYNAMIC TABLE ON SCHEMA INDUSTRIAL_LAKEHOUSE.GOLD   TO ROLE INDUSTRIAL_TRANSFORM;

-- READER: read-only on SILVER and GOLD, including objects created later
GRANT USAGE ON SCHEMA INDUSTRIAL_LAKEHOUSE.SILVER TO ROLE INDUSTRIAL_READER;
GRANT USAGE ON SCHEMA INDUSTRIAL_LAKEHOUSE.GOLD   TO ROLE INDUSTRIAL_READER;
GRANT SELECT ON FUTURE TABLES         IN SCHEMA INDUSTRIAL_LAKEHOUSE.SILVER TO ROLE INDUSTRIAL_READER;
GRANT SELECT ON FUTURE DYNAMIC TABLES IN SCHEMA INDUSTRIAL_LAKEHOUSE.SILVER TO ROLE INDUSTRIAL_READER;
GRANT SELECT ON FUTURE TABLES         IN SCHEMA INDUSTRIAL_LAKEHOUSE.GOLD   TO ROLE INDUSTRIAL_READER;
GRANT SELECT ON FUTURE DYNAMIC TABLES IN SCHEMA INDUSTRIAL_LAKEHOUSE.GOLD   TO ROLE INDUSTRIAL_READER;

-- ML: sees GOLD (the features table and the predictions table are granted in 06)
GRANT USAGE ON SCHEMA INDUSTRIAL_LAKEHOUSE.GOLD TO ROLE INDUSTRIAL_ML;

-- ── Loader service user (key-pair login, no password) ─────────────
-- Generate the key pair outside the repo (see snowflake/README.md).
-- Paste the PUBLIC key here without the BEGIN/END lines. Never paste the private key anywhere.
USE ROLE ACCOUNTADMIN;
CREATE USER IF NOT EXISTS INDUSTRIAL_LOADER
  TYPE              = SERVICE
  DEFAULT_ROLE      = INDUSTRIAL_INGEST
  DEFAULT_WAREHOUSE = INDUSTRIAL_WH
  RSA_PUBLIC_KEY    = '<PASTE_PUBLIC_KEY_HERE>';

GRANT ROLE INDUSTRIAL_INGEST TO USER INDUSTRIAL_LOADER;
GRANT ROLE INDUSTRIAL_READER TO USER INDUSTRIAL_LOADER;
GRANT ROLE INDUSTRIAL_ML     TO USER INDUSTRIAL_LOADER;